/**
 * Силуэт кузова — рисунком, а не фотографией.
 *
 * Фотографии пробовали дважды. Нарисованные ИИ оказались обобщёнными:
 * «Веста» на них была просто седаном похожей формы. Настоящие снимки
 * из открытых архивов тоже подводили — на них попадались то толпа
 * людей позади машины, то другое поколение, потому что подобрать сто
 * фотографий по описанию, не глядя на каждую, невозможно.
 *
 * Силуэт честнее их обоих. Он не притворяется конкретной машиной, а
 * показывает ровно то, что человек выбирает на этом шаге: форму кузова.
 * Седан отличается от лифтбека и универсала с первого взгляда, а годы
 * и название поколения стоят подписью рядом.
 *
 * Рисунок векторный: не грузится по сети, не устаревает, одинаково
 * чёток на любом экране и принимает цвет темы.
 */
export type BodyKind =
  | 'sedan'
  | 'hatchback'
  | 'liftback'
  | 'wagon'
  | 'crossover'
  | 'suv'
  | 'offroad'
  | 'van'
  | 'coupe'
  | 'pickup';

/*
 * Контуры кузовов — ломаными по точкам, а не кривыми.
 *
 * Профиль машины читается по нескольким ключевым местам: где кончается
 * капот, где начинается крыша, чем заканчивается корма. Ломаная задаёт
 * их прямо, и силуэт получается таким, каким задуман, — кривые же
 * приходится подбирать вслепую, и универсал выходит похожим на пикап.
 *
 * Земля на уровне 40, колёса на 40: одинаковая посадка у легковых,
 * приподнятая у внедорожников.
 */
