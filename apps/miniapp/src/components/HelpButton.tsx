export function HelpButton() {
  const [open, setOpen] = useState(false);

  return (
    <>
      <div className="help-row">
        <button
          type="button"
          className="help-button"
          onClick={() => {
            haptic.tap();
            setOpen(true);
          }}
        >
          Помощь
        </button>
      </div>

      {open && (
        <div className="sheet-backdrop" onClick={() => setOpen(false)}>
          <div className="sheet sheet--tall" onClick={(event) => event.stopPropagation()}>
            <div className="sheet__grip" aria-hidden />
            <h2 className="sheet__title">Как здесь всё устроено</h2>

            {TIPS.map((tip) => (
              <div key={tip.title} className="tip">
                <span className="tip__icon" aria-hidden>
                  {tip.icon}
                </span>
                <span className="tip__body">
                  <span className="tip__title">{tip.title}</span>
                  <span className="tip__text">{tip.text}</span>
                </span>
              </div>
            ))}

            <button type="button" className="sheet__cancel" onClick={() => setOpen(false)}>
              Понятно
            </button>
          </div>
        </div>
      )}
    </>
  );
}
