/**
 * Состояние текущего запуска приложения.
 *
 * Выбор роли сохраняется в профиле, но НЕ используется, чтобы пропустить
 * стартовый экран: человек может прийти как заказчик, а через неделю решить
 * разместить анкету. Если запомненный выбор закрывал бы экран навсегда,
 * сменить роль было бы негде — приложение оказывалось бы в тупике.
 *
 * Поэтому решение принимается заново при каждом открытии. Модульная
 * переменная подходит именно потому, что живёт ровно один запуск: Telegram
 * перезагружает страницу Mini App при повторном открытии, и она сбрасывается
 * сама. При этом переходы между экранами внутри сеанса экран выбора
 * не показывают — иначе кнопка «назад» возвращала бы на него бесконечно.
 */

let roleChosenThisSession = false;

export const isRoleChosenThisSession = (): boolean => roleChosenThisSession;

export const markRoleChosen = (): void => {
  roleChosenThisSession = true;
};

/** Возврат к выбору роли по требованию пользователя — из личного кабинета. */
export const resetRoleChoice = (): void => {
  roleChosenThisSession = false;
};
