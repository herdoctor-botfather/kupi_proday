/** Числа приходят живыми из API; если он молчит — обходимся без них. */
function describeSpecialists(count?: number): string {
  if (count === undefined) return 'Мастера в каталоге';
  if (count === 0) return 'Каталог мастеров';
  return `${count} ${plural(count, ['мастер', 'мастера', 'мастеров'])} в каталоге`;
}

function describeListings(count?: number): string {
  if (count === undefined) return 'Объявления на витрине';
  if (count === 0) return 'Витрина объявлений';
  return `${count} ${plural(count, ['объявление', 'объявления', 'объявлений'])} на витрине`;
}

function plural(count: number, forms: [string, string, string]): string {
  const mod100 = count % 100;
  const mod10 = count % 10;
  if (mod100 >= 11 && mod100 <= 14) return forms[2];
  if (mod10 === 1) return forms[0];
  if (mod10 >= 2 && mod10 <= 4) return forms[1];
  return forms[2];
}

/**
 * Имя приходит от пользователя и попадает в размеченный текст.
 * «Вася <b>» без экранирования сломал бы разметку всего сообщения,
 * и Telegram не показал бы его целиком.
 */
function escapeHtml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

